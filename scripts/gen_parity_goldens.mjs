#!/usr/bin/env node
/**
 * Generate the cross-language parity goldens in tests/fixtures/parity/goldens/ by running the
 * synthetic inputs in tests/fixtures/parity/inputs/ through the TypeScript SDK (the reference
 * implementation). The Python test suite then asserts it reproduces every expected value
 * byte-for-byte.
 *
 * Usage:
 *   node scripts/gen_parity_goldens.mjs [--ts-sdk <path>] [--check]
 *
 *   --ts-sdk  Path to a checkout of the TypeScript SDK with a built dist/ (default:
 *             ../ultrarouter-sdk-typescript, next to this repository). Build it first
 *             (npm ci && npm run build).
 *   --check   Do not write; exit 1 if a committed golden differs from the regenerated one.
 *
 * Only synthetic, public-safe inputs are used. Deterministic: the same inputs and the same
 * reference build produce byte-identical files.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const INPUTS = join(ROOT, 'tests', 'fixtures', 'parity', 'inputs');
const GOLDENS = join(ROOT, 'tests', 'fixtures', 'parity', 'goldens');

function parseArgs(argv) {
  const args = { tsSdk: resolve(ROOT, '..', 'ultrarouter-sdk-typescript'), check: false };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--ts-sdk') args.tsSdk = resolve(argv[++i]);
    else if (argv[i] === '--check') args.check = true;
    else if (argv[i] === '--help' || argv[i] === '-h') {
      process.stdout.write('usage: node scripts/gen_parity_goldens.mjs [--ts-sdk <path>] [--check]\n');
      process.exit(0);
    } else {
      process.stderr.write(`unknown argument: ${argv[i]}\n`);
      process.exit(2);
    }
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));
const contextEntry = join(args.tsSdk, 'dist', 'context.js');
const indexEntry = join(args.tsSdk, 'dist', 'index.js');
if (!existsSync(contextEntry) || !existsSync(indexEntry)) {
  process.stderr.write(
    `TypeScript SDK build not found under ${args.tsSdk}/dist (run npm ci && npm run build there, or pass --ts-sdk)\n`,
  );
  process.exit(2);
}
const ctx = await import(pathToFileURL(contextEntry).href);
const sdk = await import(pathToFileURL(indexEntry).href);

/** The custom profile the compile goldens exercise; mirrored in tests/support/profiles.py. */
const SELECTION_COUNT_PROFILE = {
  name: 'selection_count',
  orderRule: 'selection',
  memoryClasses: ctx.defineMemoryClasses(['archival']),
  kinds: ctx.defineKinds(['policy', 'fact', 'note', 'example']),
  refusals: ctx.defineRefusals({
    extraCodes: ['ACME_TOO_MANY', 'ACME_UNDATED'],
    map: (reason, detail) => {
      if (reason === 'BUDGET_EXCEEDED') return 'ACME_TOO_MANY';
      if (reason === 'AVAILABILITY_REFUSED' && detail === 'unknown') return 'ACME_UNDATED';
      return undefined;
    },
  }),
  limits: [{ kind: 'example', max: 1, label: 'one example' }],
  budget: {
    kind: 'count',
    limit: (envelope, contract) => contract.budgets.tokens ?? envelope.budgets.tokens ?? null,
  },
  serializer: ctx.defaultRenderSerializer,
  manifestEncoder: ctx.ultrarouterManifestEncoder,
  authoritativeKinds: ['policy'],
  releaseBinding: { kinds: ['policy'], facet: 'release', releaseKey: 'policy' },
  availability: { refuseUndated: true, strictModes: ['audit'] },
  defaultKindLimit: 2,
  resultCeiling: 6,
};

const PROFILES = { ultrarouter: ctx.ULTRAROUTER_PROFILE, selection_count: SELECTION_COUNT_PROFILE };

function load(name) {
  return JSON.parse(readFileSync(join(INPUTS, `${name}.json`), 'utf8'));
}

function golden(inputFile, expected) {
  return {
    _about:
      'Generated by scripts/gen_parity_goldens.mjs from the TypeScript SDK; do not edit by hand. ' +
      'expected[i] is the reference output for case i of the input file.',
    input_file: `inputs/${inputFile}.json`,
    reference: '@ultrarouter/sdk (TypeScript)',
    expected,
  };
}

const outputs = {};
/** Goldens the reference cannot produce correctly: never written; stale if one is committed. */
const notReady = [];

// learned-module placement
{
  const input = load('placement');
  outputs.placement = golden(
    'placement',
    input.cases.map(({ roles }) => {
      const messages = roles.map((role, i) => ({ role, content: `message ${i}` }));
      return {
        index: sdk.learnedPlacementIndex(messages),
        applied: sdk.applyLearnedContext(messages, input.module_content),
      };
    }),
  );
}

// hosted-prompt rendering
{
  const input = load('render');
  outputs.render = golden(
    'render',
    input.cases.map((c) =>
      sdk.renderHostedPromptResult({ template: c.template, variables: c.variables, vars: c.vars }),
    ),
  );
}

// diff statistics
{
  const input = load('diff_stats');
  outputs.diff_stats = golden(
    'diff_stats',
    input.cases.map((c) => sdk.diffStats(c.draft, c.final)),
  );
}

// canonical JSON + hashing
{
  const input = load('canonical');
  outputs.canonical = golden(
    'canonical',
    input.cases.map((c) => ({ json: ctx.canonicalJson(c.value), sha256: ctx.hashContextValue(c.value) })),
  );
}

// canonical JSON of prototype-named keys. Guarded: a reference that drops any such key (an
// assignment of "__proto__" to a plain object sets the prototype instead) never writes a golden,
// and a committed golden then fails the check as a regression.
{
  const input = load('canonical_proto');
  const expected = input.cases.map((c) => ({
    json: ctx.canonicalJson(c.value),
    sha256: ctx.hashContextValue(c.value),
  }));
  const count = (text) => text.split('"__proto__"').length - 1;
  const keepsKeys = input.cases.every((c, i) => count(expected[i].json) === count(JSON.stringify(c.value)));
  if (keepsKeys) outputs.canonical_proto = golden('canonical_proto', expected);
  else notReady.push('canonical_proto');
}

// compile
{
  const input = load('compile');
  outputs.compile = golden(
    'compile',
    input.cases.map((c) => {
      const profile = PROFILES[c.profile];
      const result = ctx.compile(c.envelope, c.contract, c.candidates, profile);
      const expected = { ok: result.ok, refusals: result.refusals, manifest: result.manifest };
      if (result.ok && result.manifest !== null) {
        const { manifestHash, ...withoutHash } = result.manifest;
        const encoded = profile.manifestEncoder(withoutHash, {
          envelope: c.envelope,
          contract: c.contract,
        });
        expected.bytes = encoded.bytes;
        expected.hash = encoded.hash;
        expected.hash_matches = encoded.hash === manifestHash;
        expected.wire = ctx.toWire(result.manifest);
        if (c.bodies !== undefined) {
          expected.rendered = ctx.render(result.manifest, new Map(Object.entries(c.bodies)));
        }
      }
      return expected;
    }),
  );
}

// lift + exit
{
  const input = load('lift');
  outputs.lift = golden(
    'lift',
    input.samples.map((s) => {
      const lifted = ctx.fromMessages(s.messages, s.hints);
      return { lifted, exited: ctx.toMessages(lifted.manifest) };
    }),
  );
}

let stale = 0;
for (const name of notReady) {
  const path = join(GOLDENS, `${name}.json`);
  if (existsSync(path)) {
    process.stderr.write(`stale: tests/fixtures/parity/goldens/${name}.json (the reference regressed)\n`);
    stale += 1;
  } else {
    process.stdout.write(`pending: tests/fixtures/parity/goldens/${name}.json (the reference is not ready yet)\n`);
  }
}
mkdirSync(GOLDENS, { recursive: true });
for (const [name, value] of Object.entries(outputs)) {
  const path = join(GOLDENS, `${name}.json`);
  const text = `${JSON.stringify(value, null, 2)}\n`;
  if (args.check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (current !== text) {
      process.stderr.write(`stale: tests/fixtures/parity/goldens/${name}.json\n`);
      stale += 1;
    }
  } else {
    writeFileSync(path, text, 'utf8');
    process.stdout.write(`wrote tests/fixtures/parity/goldens/${name}.json\n`);
  }
}
if (args.check) {
  process.stdout.write(stale === 0 ? 'parity goldens are up to date\n' : '');
  process.exit(stale === 0 ? 0 : 1);
}
