def api_coverage() -> str:
    from spec import api_key_operations, operations

    from coverage_map import COVERAGE, EXCLUDED, PROVISIONAL

    ops = operations()
    key_ops = api_key_operations()
    out = [
        GENERATED_NOTE,
        "",
        "# API coverage",
        "",
        f"Every endpoint in `openapi/openapi.yaml` that accepts an API key ({len(key_ops)} operations):",
        "the SDK method that calls it, sync and async, and the tests that call it against the mock",
        "gateway and validate the request body against the specification",
        "(`tests/test_api_coverage.py`).",
        "",
        "| Endpoint | Operation | Sync | Async | Tests |",
        "| --- | --- | --- | --- | --- |",
    ]

    def method_of(expression: str) -> str:
        call = expression.split("(", 1)[0]
        return f"{call}(...)"

    for op_id in sorted(COVERAGE, key=lambda o: (ops[o][1], ops[o][0])):
        method, path, _ = ops[op_id]
        sync = method_of(COVERAGE[op_id])
        test = f"`test_operation_sync[{op_id}]`, `test_operation_async[{op_id}]`"
        out.append(f"| `{method} {path}` | `{op_id}` | `{sync}` | `await {sync}` | {test} |")
    out += ["", "## Not wrapped", "", "| Endpoint | Operation | Reason |", "| --- | --- | --- |"]
    for op_id, reason in sorted(EXCLUDED.items()):
        method, path, _ = ops[op_id]
        out.append(f"| `{method} {path}` | `{op_id}` | {reason} |")
    out += [
        "",
        "## Learning-loop endpoints not yet in the specification",
        "",
        "The SDK calls these newer endpoints with hand-written, provisional models",
        "(`ultrarouter.types._learning`); they move to the table above when the specification",
        "gains them (`tests/test_api_coverage.py` fails until they do).",
        "",
        "| Endpoint | SDK method | Tests |",
        "| --- | --- | --- |",
    ]
    for method, path, expression, tests in PROVISIONAL:
        out.append(f"| `{method} {path}` | `{method_of(expression)}` | {tests} |")
    session_only = sorted(
        (path, method, op_id) for op_id, (method, path, op) in ops.items() if op_id not in key_ops
    )
    out += [
        "",
        "## Endpoints that do not accept an API key",
        "",
        "These operations require a dashboard session (or no authentication, for health probes), so",
        "an API-key SDK cannot call them:",
        "",
    ]
    out += [f"- `{method} {path}` (`{op_id}`)" for path, method, op_id in session_only]
    return "\n".join(out).rstrip() + "\n"


# ─────────────────────────────── llms.txt ───────────────────────────────

_ROW = re.compile(
    r"^\|\s*\[(?P<title>[^\]]+)\]\((?P<file>[\w.-]+\.md)\)\s*\|\s*(?P<desc>.+?)\s*\|\s*$"
)


def _guide_index() -> list[tuple[str, str, str, str]]:
    """(section, title, file, description) from docs/index.md tables."""
    section = ""
    rows: list[tuple[str, str, str, str]] = []
    for line in (ROOT / "docs" / "index.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        match = _ROW.match(line)
        if match:
            rows.append((section, match["title"], match["file"], match["desc"].replace("`", "")))
    return rows


def _examples() -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for path in sorted((ROOT / "examples").glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        doc = ast.get_docstring(tree) or ""
        found.append((path.name, doc.splitlines()[0] if doc else ""))
    return found


