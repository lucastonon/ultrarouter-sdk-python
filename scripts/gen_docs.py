#!/usr/bin/env python3
"""Generate the derived documentation files from the code and the hand-written docs.

Outputs (never edit them by hand):

* ``docs/api-reference.md``: every public client, namespace method, class and function, with its
  signature and docstring;
* ``docs/types-reference.md``: every response model and request shape in ``ultrarouter.types``,
  with each field's type and description;
* ``docs/api-coverage.md``: every API-key endpoint in the specification, the SDK method that calls
  it (sync and async) and the test that proves it;
* ``llms.txt`` (an llmstxt.org index) and ``llms-full.txt`` (README, AGENTS.md and every guide in
  one file).

Usage::

    uv run python scripts/gen_docs.py           # write everything
    uv run python scripts/gen_docs.py --check   # exit 1 if any output is stale
"""

