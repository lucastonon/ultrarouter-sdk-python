def llms_full_txt() -> str:
    parts = [
        "# ultrarouter Python SDK: full documentation",
        "",
        "This file concatenates README.md, AGENTS.md and every guide in docs/ (generated by",
        "scripts/gen_docs.py). The API, types and coverage references are separate files listed in",
        "llms.txt.",
        "",
    ]
    files = [ROOT / "README.md", ROOT / "AGENTS.md", ROOT / "docs" / "index.md"]
    files += [
        ROOT / "docs" / file
        for _, _, file, _ in _guide_index()
        if file not in ("api-reference.md", "types-reference.md", "api-coverage.md")
    ]
    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        parts += [
            f"<!-- file: {rel} -->",
            "",
            path.read_text(encoding="utf-8").strip(),
            "",
            "---",
            "",
        ]
    return "\n".join(parts).rstrip() + "\n"


OUTPUTS: dict[str, Callable[[], str]] = {
    "docs/api-reference.md": api_reference,
    "docs/types-reference.md": types_reference,
    "docs/api-coverage.md": api_coverage,
    "llms.txt": llms_txt,
    "llms-full.txt": llms_full_txt,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate derived documentation files.")
    parser.add_argument("--check", action="store_true", help="fail if an output is stale")
    args = parser.parse_args(argv)
    stale = []
    for rel, build in OUTPUTS.items():
        path = ROOT / rel
        content = build()
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != content:
                stale.append(rel)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("stale (run `python scripts/gen_docs.py`): " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("generated docs are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
