def types_reference() -> str:
    import ultrarouter.types as types_module
    from ultrarouter import BaseModel

    attr_docs = _attribute_docs()
    out = [
        GENERATED_NOTE,
        "",
        "# Types reference",
        "",
        "Every response model (pydantic, subclasses of `ultrarouter.BaseModel`) and request shape",
        "(`TypedDict`) in `ultrarouter.types`. Response models keep unknown fields; enumerated",
        "response values are typed `str` with the known values listed. See [Typing](typing.md).",
        "",
    ]
    names = sorted((n for n in types_module.__all__ if n != "OPERATIONS"), key=str.lower)
    for name in names:
        cls = getattr(types_module, name)
        if not _is_class(cls):
            out += [f"### {name}", "", f"`{_clean_annotation(cls)}`", ""]
            continue
        kind = "response model" if issubclass(cls, BaseModel) else "request shape (TypedDict)"
        out += [f"### {name}", "", f"*{kind}*", "", _doc(cls), ""]
        rows: list[str] = []
        if issubclass(cls, BaseModel):
            for field_name, info in cls.model_fields.items():
                annotation = cls.__annotations__.get(field_name)
                if annotation is None:
                    for base in cls.__mro__[1:]:
                        annotation = getattr(base, "__annotations__", {}).get(field_name)
                        if annotation is not None:
                            break
                wire = info.alias or field_name
                required = "yes" if info.is_required() else "no"
                description = attr_docs.get((name, field_name), "")
                rows.append(
                    f"| `{wire}` | `{_md_escape(_clean_annotation(annotation))}` | {required} | {_md_escape(description)} |"
                )
        else:
            required_keys = getattr(cls, "__required_keys__", frozenset())
            for key, annotation in cls.__annotations__.items():
                description = attr_docs.get((name, key), "")
                rows.append(
                    f"| `{key}` | `{_md_escape(_clean_annotation(annotation))}` | {'yes' if key in required_keys else 'no'} | {_md_escape(description)} |"
                )
        if rows:
            out += [
                "| Field | Type | Required | Description |",
                "| --- | --- | --- | --- |",
                *rows,
                "",
            ]
    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


