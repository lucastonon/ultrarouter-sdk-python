GENERATED_NOTE = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->"

# ─────────────────────────────── helpers ───────────────────────────────


_SECTION = re.compile(r"^(Args|Arguments|Returns|Raises|Attributes|Keys|Yields):\s*$")


def _doc(obj: Any) -> str:
    """The object's docstring converted from reST/Google style to Markdown."""
    return _to_markdown(inspect.getdoc(obj) or "")


def _to_markdown(doc: str) -> str:
    doc = re.sub(
        r":(?:class|meth|func|mod|attr|data|exc|obj):`(~?)([\w.]+)`",
        lambda m: f"`{m.group(2).rsplit('.', 1)[-1] if m.group(1) else m.group(2)}`",
        doc,
    )
    lines = doc.replace("``", "`").splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        section = _SECTION.match(line)
        if section:
            out += ["", f"**{section.group(1)}**", ""]
            i += 1
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                item = lines[i]
                if not item.strip():
                    i += 1
                    continue
                if item.startswith("        ") and out:
                    out[-1] += " " + item.strip()
                else:
                    text = item.strip()
                    name, sep, rest = text.partition(": ")
                    if sep and re.fullmatch(r"[*\w.]+", name):
                        out.append(f"- `{name}`: {rest}")
                    else:
                        out.append(
                            f"- {text}" if section.group(1) not in ("Returns", "Yields") else text
                        )
                i += 1
            out.append("")
            continue
        if line.rstrip().endswith("::"):
            stripped = line.rstrip()[:-2].rstrip()
            if stripped:
                out.append(stripped + ":")
            i += 1
            block: list[str] = []
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                block.append(lines[i][4:] if lines[i].startswith("    ") else "")
                i += 1
            while block and not block[-1].strip():
                block.pop()
            while block and not block[0].strip():
                block.pop(0)
            out += ["", "```python", *block, "```", ""]
            continue
        out.append(line)
        i += 1
    return "\n".join(out).strip()


def _clean_annotation(annotation: Any) -> str:
    if isinstance(annotation, str):
        text = annotation
    elif isinstance(annotation, typing.ForwardRef):
        text = annotation.__forward_arg__
    elif _is_class(annotation):
        text = annotation.__name__
    else:
        text = str(annotation)
    text = (
        text.replace("typing.", "")
        .replace("typing_extensions.", "")
        .replace("collections.abc.", "")
    )
    return re.sub(r"ultrarouter\.[\w.]*\.(\w+)", r"\1", text)


def _signature(func: Callable[..., Any], name: str) -> str:
    sig = inspect.signature(func)
    parts: list[str] = []
    seen_kw_only = False
    for param in sig.parameters.values():
        if param.name in ("self", "cls"):
            continue
        if param.name.startswith("_"):
            continue  # private test seams
        text = param.name
        if param.kind is inspect.Parameter.VAR_KEYWORD:
            text = "**" + text
        elif param.kind is inspect.Parameter.VAR_POSITIONAL:
            text = "*" + text
        elif param.kind is inspect.Parameter.KEYWORD_ONLY and not seen_kw_only:
            parts.append("*")
        if param.kind is inspect.Parameter.KEYWORD_ONLY:
            seen_kw_only = True
        if param.annotation is not inspect.Parameter.empty:
            text += ": " + _clean_annotation(param.annotation)
        if param.default is not inspect.Parameter.empty:
            text += " = " + _repr_default(param.default)
        parts.append(text)
    returns = ""
    if sig.return_annotation is not inspect.Signature.empty:
        returns = " -> " + _clean_annotation(sig.return_annotation)
    one_line = f"{name}({', '.join(parts)}){returns}"
    if len(one_line) <= 96:
        return one_line
    inner = ",\n".join("    " + p for p in parts)
    return f"{name}(\n{inner},\n){returns}"


def _repr_default(value: Any) -> str:
    """A stable textual default (no memory addresses)."""
    if callable(value) and hasattr(value, "__name__"):
        return str(value.__name__)
    text = repr(value)
    if " at 0x" in text:
        return type(value).__name__ + "(...)"
    return text


def _public_methods(cls: type) -> Iterator[tuple[str, Any]]:
    for name, member in cls.__dict__.items():
        if name.startswith("_"):
            continue
        if isinstance(member, property) or inspect.isfunction(member):
            yield name, member


def _block(code: str) -> str:
    return f"```python\n{code}\n```"


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _attribute_docs() -> dict[tuple[str, str], str]:
    """(class name, attribute) -> attribute docstring, parsed from the types modules' source."""
    docs: dict[tuple[str, str], str] = {}
    for module_name in ("_generated", "_chunk", "_requests", "_learning"):
        path = ROOT / "src" / "ultrarouter" / "types" / f"{module_name}.py"
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            body = node.body
            for index, statement in enumerate(body):
                if isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
                    following = body[index + 1] if index + 1 < len(body) else None
                    if (
                        isinstance(following, ast.Expr)
                        and isinstance(following.value, ast.Constant)
                        and isinstance(following.value.value, str)
                    ):
                        docs[(node.name, statement.target.id)] = inspect.cleandoc(
                            following.value.value
                        )
    return docs


