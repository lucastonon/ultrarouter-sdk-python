def _namespaces(client_cls: type) -> list[tuple[str, type]]:
    """(dotted path, resource class) for every namespace reachable from a client."""
    from ultrarouter import UltraRouter

    client = UltraRouter(api_key="ur_sk_test_reference", base_url="http://localhost")
    found: list[tuple[str, type]] = []

    def walk(obj: Any, path: str) -> None:
        for name, value in vars(obj).items():
            if name.startswith("_"):
                continue
            if type(value).__module__.startswith("ultrarouter._resources"):
                found.append((f"{path}.{name}", type(value)))
                walk(value, f"{path}.{name}")

    walk(client, "client")
    client.close()
    return found


def api_reference() -> str:
    import ultrarouter
    import ultrarouter.context as context
    from ultrarouter import AsyncUltraRouter, UltraRouter

    out: list[str] = [
        GENERATED_NOTE,
        "",
        "# API reference",
        "",
        "Every public symbol of the `ultrarouter` package, generated from the code. The async client",
        "(`AsyncUltraRouter`) has the same namespaces and methods as `UltraRouter`; its methods are",
        "coroutines (`await` them) unless noted. For response shapes see the",
        "[types reference](types-reference.md); for the endpoint each method calls see",
        "[API coverage](api-coverage.md).",
        "",
        "## Contents",
        "",
        "- [Clients](#clients)",
        "- [Namespaces](#namespaces)",
        "- [Streams, sessions and scopes](#streams-sessions-and-scopes)",
        "- [Errors](#errors)",
        "- [Helpers and constants](#helpers-and-constants)",
        "- [Context runtime](#context-runtime)",
        "",
        "## Clients",
        "",
    ]
    for cls in (UltraRouter, AsyncUltraRouter):
        out += [
            f"### {cls.__name__}",
            "",
            _block(_signature(cls.__init__, cls.__name__)),
            "",
            _doc(cls),
            "",
        ]
        for name, member in _public_methods(cls):
            if name in ("request", "request_json", "request_model", "request_text"):
                continue
            label = f"{'async ' if inspect.iscoroutinefunction(member) else ''}client.{name}"
            out += [
                f"#### {cls.__name__}.{name}",
                "",
                _block(_signature(member, label)),
                "",
                _doc(member),
                "",
            ]
        if cls is UltraRouter:
            out += [
                "Inherited from the transport: `close()`, `base_url`, `api_key`, `timeout`,",
                "`max_retries`, `default_headers`.",
                "",
            ]
    out += ["## Namespaces", ""]
    for path, cls in _namespaces(UltraRouter):
        out += [f"### {path}", "", _doc(cls), ""]
        for name, member in _public_methods(cls):
            if isinstance(member, property):
                out += [f"#### {path}.{name}", "", f"Property. {_doc(member)}", ""]
                continue
            out += [
                f"#### {path}.{name}",
                "",
                _block(_signature(member, f"{path}.{name}")),
                "",
                _doc(member),
                "",
            ]
    out += [
        "Async differences: on `AsyncUltraRouter`, `client.reviewer.record(...)` and",
        "`client.reviewer.dead_letters()` stay synchronous (they never touch the network).",
        "",
        "## Streams, sessions and scopes",
        "",
    ]
    for cls in (
        ultrarouter.Stream,
        ultrarouter.AsyncStream,
        ultrarouter.LearnedSession,
        ultrarouter.AsyncLearnedSession,
        ultrarouter.ArtifactScope,
        ultrarouter.AsyncArtifactScope,
        ultrarouter.Episode,
        ultrarouter.AsyncEpisode,
        ultrarouter.BaseModel,
    ):
        out += [f"### {cls.__name__}", "", _doc(cls), ""]
        for name, member in _public_methods(cls):
            if isinstance(member, property):
                out += [f"- `{name}` (property): {_md_escape(_doc(member))}"]
            else:
                out += [
                    f"- `{_signature(member, name)}`: {_md_escape(_doc(member).splitlines()[0] if _doc(member) else '')}"
                ]
        out += [""]
    out += ["## Errors", "", "| Class | Base | Code | Description |", "| --- | --- | --- | --- |"]
    for name in sorted(ultrarouter.__all__):
        obj = getattr(ultrarouter, name)
        if _is_class(obj) and issubclass(obj, ultrarouter.UltraRouterError):
            base = obj.__mro__[1].__name__
            code = f"`{obj.default_code}`" if obj.default_code else "(any)"
            out.append(
                f"| `{name}` | `{base}` | {code} | {_md_escape(_doc(obj).split(chr(10) + chr(10))[0])} |"
            )
    out += ["", "## Helpers and constants", ""]
    skip = {
        "UltraRouter",
        "AsyncUltraRouter",
        "Stream",
        "AsyncStream",
        "LearnedSession",
        "AsyncLearnedSession",
        "ArtifactScope",
        "AsyncArtifactScope",
        "Episode",
        "AsyncEpisode",
        "BaseModel",
        "types",
        "__version__",
    }
    for name in sorted(ultrarouter.__all__, key=str.lower):
        if name in skip:
            continue
        obj = getattr(ultrarouter, name)
        if _is_class(obj) and issubclass(obj, ultrarouter.UltraRouterError):
            continue
        if _is_class(obj) and obj.__module__.startswith("ultrarouter.types"):
            out.append(
                f"- `{name}`: response model; see the [types reference](types-reference.md#{name.lower()})."
            )
            continue
        out += _symbol(name, obj)
    out += [
        "",
        "## Context runtime",
        "",
        "`ultrarouter.context` exports (see the [context runtime guide](context-runtime.md)):",
        "",
    ]
    for name in sorted(context.__all__, key=str.lower):
        out += _symbol(name, getattr(context, name), prefix="context.")
    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


def _is_class(obj: Any) -> bool:
    """A real class; on Python 3.10 ``isinstance(dict[str, Any], type)`` is also true."""
    return isinstance(obj, type) and not isinstance(obj, types.GenericAlias)


def _symbol(name: str, obj: Any, prefix: str = "") -> list[str]:
    if inspect.isfunction(obj):
        return [f"### {prefix}{name}", "", _block(_signature(obj, name)), "", _doc(obj), ""]
    if _is_class(obj):
        lines = [f"### {prefix}{name}", "", _doc(obj), ""]
        if obj.__module__.startswith("ultrarouter") and not issubclass(obj, dict):
            for method_name, member in _public_methods(obj):
                if isinstance(member, property):
                    continue
                lines.append(f"- `{_signature(member, method_name)}`")
            lines.append("")
        return lines
    value = repr(obj)
    if " at 0x" in value:
        doc = _doc(obj)
        return [
            f"- `{prefix}{name}`: `{type(obj).__name__}` instance."
            + (f" {doc}" if doc and doc != _doc(type(obj)) else "")
        ]
    if len(value) > 200:
        value = value[:197] + "..."
    return [f"- `{prefix}{name}` = `{value}`"]


